#!/usr/bin/env python3
"""Writes bench/sample-50k.cpp: about 50 KB of C++ for the code-file bench."""
import random
import sys

random.seed(7)
out = ['// Sample C++ for the code-file bench: about 50 KB, generated by bench/make-sample-cpp.py.',
       '#include <algorithm>', '#include <string>', '#include <vector>', '']
i = 0
while sum(len(l) + 1 for l in out) < 50 * 1024:
    out += [f'// Part {i}: sums the values above a limit and reports them.',
            f'static int compute_{i}(const std::vector<int> &values, int limit)', '{',
            '    int total = 0;', '    for (size_t i = 0; i < values.size(); ++i) {',
            '        if (values[i] > limit) {', f'            total += values[i] * {random.randint(2, 9)}; // scaled',
            '        } else if (values[i] < 0) {', '            /* ignored: negative */', '            continue;', '        }', '    }',
            f'    std::string label = "part {i}: \\"total\\"";', '    return label.empty() ? 0 : total;', '}', '']
    i += 1
open(sys.argv[1] if len(sys.argv) > 1 else 'bench/sample-50k.cpp', 'w').write('\n'.join(out))
